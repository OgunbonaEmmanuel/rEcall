import {chromium,expect} from '@playwright/test';
import {spawn} from 'node:child_process';
import {mkdir,writeFile,open} from 'node:fs/promises';
import path from 'node:path';
const root=process.cwd(),run=path.join(root,'artifacts',`browser-extensions-${Date.now()}`);
await mkdir(run,{recursive:true});
const log=await open(path.join(run,'server.log'),'w');
const server=spawn(path.join(root,'.venv','Scripts','python.exe'),['-m','uvicorn','backend.app:app','--host','127.0.0.1','--port','8769'],{cwd:root,windowsHide:true,env:{...process.env,RECALL_DATA:path.join(run,'data')},stdio:['ignore',log.fd,log.fd]});
const base='http://127.0.0.1:8769',checks={},errors=[];
let browser;
try{
  await expect.poll(async()=>{try{return(await fetch(base+'/api/health')).ok;}catch{return false;}},{timeout:30000}).toBe(true);
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  const names=['IMG_4821.jpg','IMG_5932.jpg','IMG_6104.jpg','IMG_7785.jpg','download_42.docx'];
  await page.locator('#file-upload').setInputFiles(names.map(n=>path.join(root,'fixtures','generated','extensions',n)));
  await expect.poll(async()=>{const docs=await(await fetch(base+'/api/files')).json();return docs.length===5&&docs.every(f=>f.status==='ready');},{timeout:240000,intervals:[1000]}).toBe(true);
  await expect(page.locator('.processing-banner')).toHaveCount(0,{timeout:10000});
  checks.upload_docx_and_images=true;
  async function search(q,mode){
    await page.getByRole('textbox',{name:'Search your files'}).fill(q);
    await page.getByRole('group',{name:'Search mode'}).getByRole('button',{name:mode,exact:true}).click();
    await expect(page.locator('.library')).toHaveAttribute('aria-busy','false');
    await page.getByRole('heading',{name:'What we found'}).waitFor();
  }
  await search('a dog playing outside','Visual');
  await expect(page.locator('.file-name').first()).toHaveText('IMG_4821.jpg');
  await page.getByRole('button',{name:'Preview IMG_4821.jpg',exact:true}).click();
  await page.locator('.visual-evidence').waitFor();
  await expect(page.locator('.source-box')).toHaveCount(0);
  await expect(page.locator('.extracted-text')).toHaveCount(0);
  checks.visual_has_no_text_evidence=true;
  await page.screenshot({path:path.join(run,'visual-preview.png'),fullPage:true});
  await page.getByRole('button',{name:'Reindex visual',exact:true}).click();
  await expect(page.getByRole('button',{name:'Cancel processing',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Cancel processing',exact:true}).click();
  await expect(page.getByRole('button',{name:'Reindex visual',exact:true})).toBeVisible();
  checks.reindex_and_cancel=true;
  await page.keyboard.press('Escape');
  await search('127.45','Text');
  await page.getByRole('button',{name:'Preview download_42.docx',exact:true}).click();
  await page.getByLabel('DOCX text preview').waitFor();
  await expect(page.locator('.source-method').filter({hasText:'Table 1, row 1, cell 2'})).toBeVisible();
  await expect(page.locator('.page-controls')).toHaveCount(0);
  await expect(page.locator('.source-box')).toHaveCount(0);
  await expect(page.getByLabel('DOCX text preview').locator('img')).toHaveCount(0);
  checks.docx_sources_no_fake_pages=true;
  checks.untrusted_text_inert=true;
  const download=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download original'}).click();
  if((await download).suggestedFilename()!=='download_42.docx')throw Error('Wrong download name');
  checks.docx_download=true;
  await page.screenshot({path:path.join(run,'docx-preview.png'),fullPage:true});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Clear search'}).click();
  await page.getByRole('button',{name:'DOCX',exact:true}).click();
  await expect(page.locator('.file-card')).toHaveCount(1);
  checks.docx_filter=true;
  await page.locator('#file-upload').setInputFiles({name:'malformed.docx',mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',buffer:Buffer.from('PKnot-a-zip')});
  await expect(page.getByRole('alert')).toContainText('Malformed DOCX');
  checks.docx_validation_feedback=true;
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(run,'mobile.png'),fullPage:true});
  if(!await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))throw Error('Horizontal overflow');
  checks.mobile=true;
  checks.no_js_errors=errors.length===0;
  if(errors.length)throw Error(errors.join('\n'));
  console.log(JSON.stringify({checks,errors,artifacts:run},null,2));
}finally{
  await writeFile(path.join(root,'artifacts','browser-extensions-verification.json'),JSON.stringify({checks,errors,artifacts:run},null,2));
  await browser?.close();server.kill();await log.close();
}
