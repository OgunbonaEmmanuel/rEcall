import { chromium, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import { mkdir, writeFile, open } from 'node:fs/promises';
import path from 'node:path';
const root = process.cwd();
const run = path.join(root, 'artifacts', `browser-${Date.now()}`);
await mkdir(run, { recursive: true });
const log = await open(path.join(run,'server.log'),'w');
const python = path.join(root,'.venv','Scripts','python.exe');
const server = spawn(python,['-m','uvicorn','backend.app:app','--host','127.0.0.1','--port','8767'],{
  cwd:root, windowsHide:true, env:{...process.env,RECALL_DATA:path.join(run,'data')}, stdio:['ignore',log.fd,log.fd]
});
const base='http://127.0.0.1:8767';
let browser;
const checks={}, errors=[];
const assert=(test,label)=>{checks[label]=Boolean(test);if(!test)throw new Error(label);};
try {
  let ready=false;
  for(let i=0;i<100;i++){try{if((await fetch(base+'/api/health')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,200));}
  assert(ready,'server_ready');
  browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByRole('heading',{name:'Make room for a little recall'}).waitFor();
  await page.screenshot({path:path.join(run,'01-empty.png'),fullPage:true});
  await page.keyboard.press('Control+k');
  assert(await page.getByRole('textbox',{name:'Search your files'}).evaluate(el=>document.activeElement===el),'keyboard_search_shortcut');
  const names=['IMG_4821.png','Screenshot_108.png','ticket_09.jpg','image_110.jpeg','Screenshot_201.png','IMG_0000.png','scan_023.pdf','download_7.pdf','document_12.pdf','note_62.pdf'];
  await page.locator('#file-upload').setInputFiles(names.map(n=>path.join(root,'fixtures','generated',n)));
  await page.getByText('10 files added.',{exact:true}).waitFor({timeout:30000});
  await expect.poll(async()=>{const docs=await(await fetch(base+'/api/files')).json();return docs.length===10&&docs.every(d=>d.status==='ready');},{timeout:240000,intervals:[1000]}).toBe(true);
  await expect(page.locator('.processing-banner')).toHaveCount(0,{timeout:10000});
  await page.getByRole('button',{name:'Preview IMG_4821.png',exact:true}).waitFor();
  await page.screenshot({path:path.join(run,'02-library.png'),fullPage:true});
  checks.multi_upload=true;
  async function search(q){await page.getByRole('textbox',{name:'Search your files'}).fill(q);await page.getByRole('button',{name:'Search',exact:true}).click();await page.getByRole('heading',{name:'What we found'}).waitFor();await page.waitForFunction(()=>document.querySelector('.library')?.getAttribute('aria-busy')==='false');}
  await search('headphone receipt');
  assert((await page.locator('.file-name').first().textContent())==='IMG_4821.png','keyword_top_result');
  await page.getByRole('button',{name:'Preview IMG_4821.png',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.locator('.source-box').first().waitFor();
  checks.source_highlight=true;
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download original'}).click();
  const download=await downloadEvent;
  assert(download.suggestedFilename()==='IMG_4821.png','original_download');
  await page.keyboard.press('Escape');
  assert(await page.getByRole('dialog').count()===0,'escape_closes_preview');
  await search('proof I paid for wireless audio gear');
  await page.screenshot({path:path.join(run,'03-semantic.png'),fullPage:true});
  assert((await page.locator('.file-name').first().textContent())==='IMG_4821.png','paraphrase_top_result');
  assert(await page.getByText('Semantic match',{exact:false}).count()>0,'semantic_explanation');
  await search('cancellation policy');
  await page.getByRole('button',{name:'Preview download_7.pdf',exact:true}).click();
  await page.getByText('Page 2 / 2',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Previous page'}).click();
  await page.getByText('Page 1 / 2',{exact:true}).waitFor();
  checks.pdf_page_navigation=true;
  await page.keyboard.press('Escape');
  await page.locator('#file-upload').setInputFiles(path.join(root,'fixtures','generated','IMG_4821.png'));
  await page.getByText('0 files added · 1 duplicate already in your library.',{exact:true}).waitFor();
  checks.duplicate_feedback=true;
  await page.locator('#file-upload').setInputFiles({name:'broken.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.7 corrupted browser fixture')});
  await page.getByRole('button',{name:'Clear search'}).click();
  const broken=page.locator('.file-card').filter({has:page.getByRole('button',{name:'broken.pdf',exact:true})});
  await broken.getByRole('button',{name:'Retry',exact:true}).waitFor({timeout:30000});
  const retryResponse=page.waitForResponse(r=>r.url().endsWith('/retry')&&r.request().method()==='POST');
  await broken.getByRole('button',{name:'Retry',exact:true}).click();
  await retryResponse;
  await expect.poll(async()=>{const docs=await(await fetch(base+'/api/files')).json();return docs.find(d=>d.name==='broken.pdf')?.status;},{timeout:30000,intervals:[500]}).toBe('failed');
  await broken.getByRole('button',{name:'Retry',exact:true}).waitFor({timeout:10000});
  checks.failure_and_retry=true;
  await search('zxqv778899 nonexistent unicorn astronaut');
  await page.getByRole('heading',{name:'No files found just yet'}).waitFor();
  checks.no_results=true;
  await search('headphone receipt');
  await page.getByRole('button',{name:'Preview IMG_4821.png',exact:true}).click();
  await page.getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('button',{name:'Keep file'}).click();
  checks.delete_cancel=true;
  await page.getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('button',{name:'Delete permanently'}).click();
  await page.getByText('File deleted, including its original, previews, text and search entries.').waitFor();
  await page.reload();
  await page.getByRole('button',{name:'Preview scan_023.pdf',exact:true}).waitFor();
  assert(await page.getByRole('button',{name:'Preview IMG_4821.png',exact:true}).count()===0,'deleted_after_reload');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Images',exact:true}).click();
  await page.screenshot({path:path.join(run,'04-mobile.png'),fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile_no_horizontal_overflow');
  const cards=await page.locator('.file-type').allTextContents();
  assert(cards.length>0&&cards.every(t=>!t.includes('PDF')),'image_filter');
  await page.setViewportSize({width:1440,height:1050});
  await page.getByRole('button',{name:'All files',exact:true}).last().click();
  await page.getByRole('button',{name:/Curious what Recall can find/}).click();
  await page.getByRole('heading',{name:'Demo collection'}).waitFor();
  await expect.poll(async()=>{const docs=await(await fetch(base+'/api/files')).json();return docs.filter(d=>d.demo&&d.status==='ready').length;},{timeout:60000,intervals:[1000]}).toBe(10);
  await expect(page.locator('.demo-tag')).toHaveCount(10,{timeout:10000});
  checks.demo_collection_labelled=true;
  await page.screenshot({path:path.join(run,'05-demo.png'),fullPage:true});
  assert(errors.length===0,'no_browser_exceptions');
  console.log(JSON.stringify({checks,errors,artifacts:run},null,2));
} finally {
  await writeFile(path.join(root,'artifacts','browser-verification.json'),JSON.stringify({checks,errors,artifacts:run},null,2));
  await browser?.close(); server.kill(); await log.close();
}
